use sales;
drop table auto_sales;

select * from auto_sales;

SELECT
    ORDERNUMBER,
    PRODUCTCODE,
    ORDERLINENUMBER,
    COUNT(*) AS duplicate_count      #### for duplicate rows
FROM auto_sales
GROUP BY
    ORDERNUMBER,
    PRODUCTCODE,
    ORDERLINENUMBER
HAVING COUNT(*) > 1;

SELECT *
FROM auto_sales
WHERE customername IS NULL  #### checking for missing valus
   OR phone IS NULL
   OR city IS NULL;

SELECT
    SUM(CASE WHEN ORDERNUMBER IS NULL THEN 1 ELSE 0 END) AS ORDERNUMBER_NULLS,
    SUM(CASE WHEN QUANTITYORDERED IS NULL THEN 1 ELSE 0 END) AS QUANTITYORDERED_NULLS,
    SUM(CASE WHEN PRICEEACH IS NULL THEN 1 ELSE 0 END) AS PRICEEACH_NULLS,
    SUM(CASE WHEN SALES IS NULL THEN 1 ELSE 0 END) AS SALES_NULLS,
    SUM(CASE WHEN ORDERDATE IS NULL THEN 1 ELSE 0 END) AS ORDERDATE_NULLS,
    SUM(CASE WHEN CUSTOMERNAME IS NULL THEN 1 ELSE 0 END) AS CUSTOMERNAME_NULLS,
    SUM(CASE WHEN PHONE IS NULL THEN 1 ELSE 0 END) AS PHONE_NULLS,
    SUM(CASE WHEN CITY IS NULL THEN 1 ELSE 0 END) AS CITY_NULLS,
    SUM(CASE WHEN COUNTRY IS NULL THEN 1 ELSE 0 END) AS COUNTRY_NULLS
    from auto_sales;
    
    UPDATE auto_sales
SET
    STATUS = TRIM(STATUS),
    PRODUCTLINE = TRIM(PRODUCTLINE),
    CUSTOMERNAME = TRIM(CUSTOMERNAME),
    ADDRESSLINE1 = TRIM(ADDRESSLINE1),  #### tim extra spaces
    CITY = TRIM(CITY),
    COUNTRY = TRIM(COUNTRY),
    CONTACTLASTNAME = TRIM(CONTACTLASTNAME),
    CONTACTFIRSTNAME = TRIM(CONTACTFIRSTNAME),
    DEALSIZE = TRIM(DEALSIZE);

SELECT *
FROM auto_sales
WHERE TRIM(STATUS) = ''
   OR TRIM(PRODUCTLINE) = ''
   OR TRIM(CUSTOMERNAME) = ''
   OR TRIM(CITY) = ''
   OR TRIM(COUNTRY) = '';     ### for blank values
   
   SELECT DISTINCT STATUS
FROM auto_sales
ORDER BY STATUS;

SELECT DISTINCT DEALSIZE
FROM auto_sales
ORDER BY DEALSIZE;          ###### checking inconsistent values

SELECT DISTINCT COUNTRY
FROM auto_sales
ORDER BY COUNTRY;




















































































